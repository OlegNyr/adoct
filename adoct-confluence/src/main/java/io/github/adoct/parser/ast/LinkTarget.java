package io.github.adoct.parser.ast;

/**
 * Экранирование адреса ссылки для разметки.
 * <p>
 * У макроса {@code link:цель[подпись]} цель обрывается на первом пробеле, а квадратные скобки
 * закрывают список атрибутов, — поэтому ссылка на файл или папку с пробелом в имени (обычное дело
 * для заголовков страниц Confluence) вообще не распознаётся как ссылка и утекает в текст как есть.
 * В Markdown адрес ссылки точно так же не может содержать пробел. Кодируем процентами только эти
 * символы: остальное (в том числе уже готовые {@code %XX} в URL из Confluence) трогать нельзя,
 * иначе получится двойное кодирование.
 * <p>
 * Картинок это не касается: у {@code image:}/{@code image::} цель читается до {@code [}, пробелы
 * допустимы, и AsciiDoctor кодирует их сам при рендере в {@code src}.
 */
final class LinkTarget {

  private LinkTarget() {
  }

  static String encode(String target) {
    if (target == null || target.isEmpty()) {
      return target;
    }
    return target.replace(" ", "%20").replace("[", "%5B").replace("]", "%5D");
  }
}
